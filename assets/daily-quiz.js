// 날짜 문자열 → 시드 고정 난수 (같은 날짜면 항상 같은 순서)
function quizRandom(seedStr) {
    let h = 2166136261;
    for (let i = 0; i < seedStr.length; i++) { h ^= seedStr.charCodeAt(i); h = Math.imul(h, 16777619); }
    return () => {
        h += 0x6D2B79F5; let t = h;
        t = Math.imul(t ^ (t >>> 15), t | 1); t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
        return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
    };
}
function quizShuffle(arr, rnd) {
    const a = arr.slice();
    for (let i = a.length - 1; i > 0; i--) { const j = Math.floor(rnd() * (i + 1)); [a[i], a[j]] = [a[j], a[i]]; }
    return a;
}
// 그날의 5문제: 상황형 3 + 심화 2, 보기 순서도 섞어서 answer(정답 위치)를 함께 돌려줌
function buildDailyQuiz(dateStr) {
    const rnd = quizRandom('outofstock-quiz-' + dateStr);
    const pick = (type, n) => quizShuffle(QUIZ_BANK.filter((q) => q.type === type), rnd).slice(0, n);
    return [...pick('case', 3), ...pick('deep', 2)].map((q) => {
        const order = quizShuffle([0, 1, 2, 3], rnd);
        return { ...q, options: order.map((i) => q.options[i]), answer: order.indexOf(0) };
    });
}
