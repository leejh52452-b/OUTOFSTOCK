def _accuracy(classify, cases):
    got = classify([t for t, _ in cases])
    return sum(g.label == y for g, (_, y) in zip(got, cases)) / len(cases)


def test_eval_set_v2_beats_v1():
    v1 = _accuracy(lambda ts: [S._lexicon_v1(t) for t in ts], CASES)
    v2 = _accuracy(S.LexiconClassifier().classify, CASES)
    assert len(CASES) == 120
    assert v2 >= 0.9 and v2 - v1 >= 0.25, (v1, v2)


