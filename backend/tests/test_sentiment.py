def test_old_lexicon_rows_are_relabeled():
    """사전을 바꾸면 예전 사전으로 매긴 라벨은 다음 배치에서 다시 매김(모델 결과는 그대로)."""
    from app.services.themes import classify_news
    db.execute("INSERT INTO news(news_id, title, url) VALUES(1, 'LG, 적자폭 축소', 'u1'), "
               "(2, '카카오 신작 흥행', 'u2'), (3, 'FDA 승인 불발', 'u3')")
    db.execute("INSERT INTO news_sentiment(news_id, label, score, model, classified_at) VALUES "
               "(1, 'NEG', -1, 'lexicon-v1', '2026-10-01T09:00:00'), (3, 'POS', 0.9, 'kr-finbert-sc', '2026-10-01T09:00:00')")
    r = classify_news()
    assert r["classified"] == 2 and r["model"] == S.LexiconClassifier.name
    got = {x["news_id"]: (x["label"], x["model"]) for x in db.query("SELECT news_id, label, model FROM news_sentiment")}
    assert got[1] == ("POS", S.LexiconClassifier.name)          # v1 오분류 → 다시 매김
    assert got[2][0] == "POS"                                     # 새 기사
    assert got[3] == ("POS", "kr-finbert-sc")                     # 모델 결과는 건드리지 않음
    assert classify_news()["classified"] == 0                     # 멱등
